/**
 * One-off migration script: fix city/state for existing locations.
 *
 * Usage:  node scripts/fix-location-cities.mjs
 *
 * What it does:
 *  1. Fetches all locations from Supabase (read-only, anon key)
 *  2. Reverse-geocodes each lat/lng via Nominatim
 *  3. Outputs SQL UPDATE statements to stdout
 *  4. You review the SQL, then paste into Supabase SQL Editor
 *
 * Rate limit: 1 request/second (Nominatim public tier)
 */

const SUPABASE_URL = 'https://ixncaswdwpxfazhzagqu.supabase.co';
const SUPABASE_ANON_KEY = 'sb_publishable_0OyPi7C54jH4mHPY8YOGXQ_TShnKLOw';

async function main() {
  // ── Fetch all locations ──
  console.error('Fetching locations...');
  const res = await fetch(
    `${SUPABASE_URL}/rest/v1/locations?select=id,name,latitude,longitude,city,state&order=created_at.asc`,
    {
      headers: {
        apikey: SUPABASE_ANON_KEY,
        Authorization: `Bearer ${SUPABASE_ANON_KEY}`,
      },
    },
  );
  if (!res.ok) {
    console.error(`Failed to fetch locations: ${res.status} ${res.statusText}`);
    process.exit(1);
  }
  const locations = await res.json();
  console.error(`Found ${locations.length} locations.\n`);

  const updates = [];

  for (const loc of locations) {
    console.error(`  Reverse-geocoding: ${loc.name} (${loc.latitude}, ${loc.longitude})...`);
    try {
      const geoRes = await fetch(
        `https://nominatim.openstreetmap.org/reverse?lat=${loc.latitude}&lon=${loc.longitude}&format=json`,
        { headers: { 'User-Agent': 'DriftScout/1.0 (migration script)' } },
      );
      if (!geoRes.ok) {
        console.error(`    ⚠ Nominatim error ${geoRes.status}, skipping`);
        continue;
      }
      const data = await geoRes.json();
      const addr = data?.address;
      if (!addr) {
        console.error('    ⚠ No address data, skipping');
        continue;
      }
      const city = addr.city || addr.town || addr.village || addr.hamlet || '';
      const state = addr.state || '';

      const oldCity = loc.city || '';
      const oldState = loc.state || '';

      if (city === oldCity && state === oldState) {
        console.error(`    ✓ Already correct: "${city}, ${state}"`);
        continue;
      }

      console.error(`    → "${oldCity}, ${oldState}" → "${city}, ${state}"`);
      updates.push({ id: loc.id, name: loc.name, city, state });
    } catch (err) {
      console.error(`    ⚠ Error: ${err.message}, skipping`);
    }

    // Rate limit: 1 request/second
    if (locations.indexOf(loc) < locations.length - 1) {
      await new Promise((r) => setTimeout(r, 1100));
    }
  }

  // ── Output SQL ──
  if (updates.length === 0) {
    console.error('\nAll locations already correct — nothing to update.');
    return;
  }

  console.error(`\n${updates.length} location(s) need updating. SQL below:\n`);
  console.log('-- Fix city/state for existing locations');
  console.log('-- Generated by scripts/fix-location-cities.mjs\n');
  for (const u of updates) {
    const escapedName = u.name.replace(/'/g, "''");
    const escapedCity = u.city.replace(/'/g, "''");
    const escapedState = u.state.replace(/'/g, "''");
    console.log(
      `UPDATE locations SET city = '${escapedCity}', state = '${escapedState}' WHERE id = '${u.id}'; -- ${escapedName}`,
    );
  }
  console.log('');
}

main();
